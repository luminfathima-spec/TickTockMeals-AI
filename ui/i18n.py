def t(key: str, lang: str = "en", **kwargs: Any) -> str:
    """Retrieve localized string with keyword interpolation and English fallback."""
    norm_lang = lang.lower() if lang.lower() in TRANSLATIONS else "en"
    lang_dict = TRANSLATIONS.get(norm_lang, TRANSLATIONS["en"])
    text_template = lang_dict.get(key, TRANSLATIONS["en"].get(key, key))
    if kwargs:
        try:
            return text_template.format(**kwargs)
        except Exception:
            return text_template
    return text_template
